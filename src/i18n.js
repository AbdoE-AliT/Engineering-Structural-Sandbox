export function getLanguage() {
  return 'en';
}

export function setLanguage(language) {
  return language === 'ar' ? 'ar' : 'en';
}

const originalText = new WeakMap();
const appliedText = new WeakMap();
const originalAttributes = new WeakMap();
const appliedAttributes = new WeakMap();
let activeLanguage = getLanguage();
let observer;

function localizeTextNode(node) {
  const current = node.nodeValue;
  const previous = appliedText.get(node);
  if (!originalText.has(node) || (previous !== undefined && current !== previous)) {
    originalText.set(node, current);
  }
  const source = originalText.get(node);
  const trimmed = source.trim();
  const translated = translateText(trimmed, activeLanguage);
  const next = translated === trimmed ? source
    : `${source.slice(0, source.indexOf(trimmed))}${translated}${source.slice(source.indexOf(trimmed) + trimmed.length)}`;
  if (current !== next) node.nodeValue = next;
  appliedText.set(node, next);
}

function localizeAttributes(element) {
  for (const name of ['title', 'placeholder', 'aria-label']) {
    if (!element.hasAttribute(name)) continue;
    const current = element.getAttribute(name);
    let originals = originalAttributes.get(element);
    let applied = appliedAttributes.get(element);
    if (!originals) originalAttributes.set(element, originals = new Map());
    if (!applied) appliedAttributes.set(element, applied = new Map());
    if (!originals.has(name) || (applied.has(name) && current !== applied.get(name))) {
      originals.set(name, current);
    }
    const next = translateText(originals.get(name), activeLanguage);
    if (current !== next) element.setAttribute(name, next);
    applied.set(name, next);
  }
}

function localizeTree(root, language = activeLanguage) {
  activeLanguage = language;
  const visit = node => {
    if (node.nodeType === Node.TEXT_NODE) {
      localizeTextNode(node);
      return;
    }
    if (node.nodeType !== Node.ELEMENT_NODE && node !== document) return;
    if (node.nodeType === Node.ELEMENT_NODE) localizeAttributes(node);
    for (const child of node.childNodes) visit(child);
  };
  visit(root);
}

export function initializeLocalization(onChange = () => {}) {
  const selectors = [...document.querySelectorAll('[data-language-select]')];
  if (!selectors.length) return;
  for (const selector of selectors) selector.value = activeLanguage;
  document.documentElement.lang = activeLanguage;
  document.documentElement.dir = activeLanguage === 'ar' ? 'rtl' : 'ltr';
  document.title = translateText(document.title, activeLanguage);
  localizeTree(document.body);
  observer = new MutationObserver(records => {
    for (const record of records) {
      if (record.type === 'characterData') localizeTextNode(record.target);
      if (record.type === 'attributes') localizeAttributes(record.target);
      for (const node of record.addedNodes || []) localizeTree(node);
    }
  });
  observer.observe(document.body, {
    subtree: true, childList: true, characterData: true, attributes: true,
    attributeFilter: ['title', 'placeholder', 'aria-label']
  });
  for (const selector of selectors) selector.addEventListener('change', () => {
    activeLanguage = setLanguage(selector.value);
    for (const picker of selectors) picker.value = activeLanguage;
    document.documentElement.lang = activeLanguage;
    document.documentElement.dir = activeLanguage === 'ar' ? 'rtl' : 'ltr';
    localizeTree(document.body);
    onChange(activeLanguage);
  });
}
